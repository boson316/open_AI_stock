"""Synthetic version/period tests, never published as financial observations."""
from datetime import date
import pytest
from openstock.models import Fact
from openstock.normalize import quarters
from openstock.tsm_cash import parse_statement


def cash(end,value,accession,**changes):
    return Fact(metric='ocf',value=value,unit='USD',start='2024-01-01',end=end,filed='2025-02-01',
        accession=accession,tag='us-gaap:OperatingCashFlow',source='https://www.sec.gov/'+accession,form='10-K',
        report_fiscal_year=2024,reporting_basis='US GAAP').model_copy(update=changes)


def test_cash_cohort_q4_lineage_and_availability():
    a=cash('2024-09-30',90,'q3');b=cash('2024-12-31',140,'annual')
    assert quarters([a,b],date(2025,1,31))==[]
    f=quarters([a,b])[0]
    assert f.value==50 and f.start==date(2024,10,1) and len(f.source_refs)==2
    assert f.filed==b.filed and 'FY2024' in f.lineage[0]


@pytest.mark.parametrize('change',[{'report_fiscal_year':2025},{'reporting_basis':'IFRS (IASB)'},{'unit':'TWD'},{'tag':'other:Cash'},{'form':'10-K/A'}])
def test_cash_rejects_incompatible_operands(change):
    assert quarters([cash('2024-09-30',90,'q3'),cash('2024-12-31',140,'annual',**change)])==[]


def test_cash_conflicting_vintage_blocks_subtraction():
    a=cash('2024-09-30',90,'q3');revised=cash('2024-09-30',95,'q3-revised')
    assert quarters([a,revised,cash('2024-12-31',140,'annual')])==[]


def test_tifrs_consolidated_thousands_and_split_parentheses():
    doc={'intro':'Consolidated balance sheets','unit_evidence':['In Thousands of New Taiwan Dollars'],
        'source':'https://www.sec.gov/test-only','filed':'2025-08-01','accession':'synthetic','sha256':'synthetic',
        'tables':[[['Six Months Ended June 30'],['2025','2024'],
                   ['Net cash used in investing activities','(','120',')','','(90',')'],
                   ['Net cash generated by operating activities','200','','180']]]}
    fs=parse_statement(doc)
    assert [(f.metric,f.value) for f in fs]==[('icf',-120000),('icf',-90000),('ocf',200000),('ocf',180000)]
    assert all(f.end.month==6 and f.reporting_basis=='TIFRS' for f in fs)
    assert parse_statement({**doc,'intro':'Parent company only consolidated'})==[]
    with pytest.raises(ValueError):parse_statement({**doc,'unit_evidence':[]})


def _fact(metric,value,start,end,tag,**kw):
    base=dict(metric=metric,value=value,unit='USD',start=start,end=end,filed='2030-01-01',accession='acc',tag=tag,
        source='https://www.sec.gov/Archives/edgar/data/1/acc-index.html',form='10-K',reporting_basis='US GAAP')
    return Fact(**{**base,**kw})


def test_gross_margin_gate_requires_same_period_gross_profit_not_operating_income():
    from types import SimpleNamespace
    from openstock.coverage import audit_gross_margin
    ends=[date(2021+i//4,[3,6,9,12][i%4],[31,30,30,31][i%4]) for i in range(20)]
    facts=[]
    for e in ends:
        s=date(e.year,e.month-2,1)
        facts+= [_fact('revenue',100,s,e,'us-gaap:Revenues'),_fact('gross_profit',40,s,e,'us-gaap:GrossProfit'),_fact('operating_income',10,s,e,'us-gaap:OperatingIncomeLoss')]
    ds=SimpleNamespace(ticker='XYZ',currency='USD',facts=facts)
    ok=audit_gross_margin(ds,facts)
    assert ok['complete'] and ok['quarters']==20 and ok['periods'][0]['margin_pct']==40
    # Missing one quarter breaks the gate rather than silently shortening the line.
    short=[f for f in facts if not (f.metric=='gross_profit' and f.end==ends[5])]
    assert not audit_gross_margin(SimpleNamespace(ticker='XYZ',currency='USD',facts=short),short)['complete']
    # Operating income substituted for gross profit is rejected.
    subst=[f.model_copy(update={'value':10}) if f.metric=='gross_profit' and f.end==ends[3] else f for f in facts]
    r=audit_gross_margin(SimpleNamespace(ticker='XYZ',currency='USD',facts=subst),subst)
    assert not r['complete'] and any('operating income' in e for e in r['errors'])
    # Unreviewed concept is rejected.
    odd=[f.model_copy(update={'tag':'us-gaap:OperatingIncomeLoss'}) if f.metric=='gross_profit' and f.end==ends[2] else f for f in facts]
    assert not audit_gross_margin(SimpleNamespace(ticker='XYZ',currency='USD',facts=odd),odd)['complete']


def test_gross_margin_not_applicable_for_financials_and_never_substituted():
    from types import SimpleNamespace
    from openstock.coverage import audit_gross_margin
    ds=SimpleNamespace(ticker='SOFI',currency='USD',facts=[])
    r=audit_gross_margin(ds,[])
    assert r['status']=='not_applicable' and r['complete'] and r['periods']==[]
    stray=SimpleNamespace(ticker='SOFI',currency='USD',facts=[_fact('gross_profit',1,date(2024,1,1),date(2024,3,31),'us-gaap:GrossProfit')])
    assert not audit_gross_margin(stray,[])['complete']


def test_published_datasets_pass_every_coverage_gate():
    import json
    from pathlib import Path
    cov=json.loads((Path(__file__).parents[2]/'public/data/coverage.json').read_text())
    assert cov['complete'] and cov['cashflow_complete'] and cov['gross_margin_complete']
    assert len(cov['companies'])==13
    for c in cov['companies']:
        assert c['cashflow']['complete'] and c['cashflow']['quarters']==20,c['ticker']
        for p in c['cashflow']['periods']:
            m=p['metrics']
            assert set(m)=={'ocf','icf','financing_cf','capex','sbc'},(c['ticker'],p['end'])
            assert abs(p['fcf']-(m['ocf']['value']-abs(m['capex']['value'])))<1e-6
        gm=c['gross_margin']
        if c['ticker']=='SOFI':
            assert gm['status']=='not_applicable'
        else:
            assert gm['complete'] and gm['quarters']==20,c['ticker']
            assert all(p['source'] and p['margin_pct']<100 for p in gm['periods'])
